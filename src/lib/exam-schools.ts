export const EXAM_SCHOOL_GROUPS = [
  "高校・高専",
  "大学・短大・専門",
  "医療・看護",
  "公務員・防衛",
  "そのほか",
] as const;

export function isExamSchoolType(v: unknown): v is ExamSchoolType {
  return typeof v === "string" && v in EXAM_SCHOOL_TYPES;
}

/** 学校名から種類を推測する（選ばれていないときの初期値。外れたら本人が選び直す） */
export function guessSchoolType(name: string | undefined | null): ExamSchoolType | null {
  const n = (name ?? "").trim();
  if (!n) return null;
  if (/高等工科学校/.test(n)) return "jsdf_high";
  if (/防衛大学校|防衛医科大学校/.test(n)) return "defense_univ";
  if (/警察/.test(n)) return "police";
  if (/消防/.test(n)) return "fire";
  if (/助産/.test(n)) return "midwife";
  if (/看護/.test(n)) return "nursing";
  if (/高等専門学校|高専/.test(n)) return "kosen";
  if (/大学院/.test(n)) return "graduate";
  if (/短期大学/.test(n)) return "junior_college";
  if (/専門学校/.test(n)) return "vocational";
  if (/高等学校|高校|学院高|学園高/.test(n))
    return /県立|都立|府立|道立|市立|町立/.test(n) ? "hs_public" : "hs_private";
  if (/大学/.test(n)) return "univ_recommend";
  return null;
}

/** 受験生の練習の面接官への指示（学校の種類と、志望校について調べた内容から作る） */
export function examInterviewerPrompt(args: {
  type: ExamSchoolType;
  schoolName: string | null;
  faculty: string | null;
  schoolInfo: string | null;
  styleInstruction: string;
  depthInstruction: string;
  timeInstruction: string;
}): string {
  const d = EXAM_SCHOOL_TYPES[args.type];
  const school = args.schoolName
    ? `「${args.schoolName}」${args.faculty ? `（${args.faculty}）` : ""}`
    : "志望校";
  const stageWord =
    d.stage === "中学" ? "中学校" : d.stage === "高校" ? "高校" : "大学（今の学校）";
  return `あなたは${school}の${d.interviewer}です。これは本番ではなく、受験生のための模擬面接（練習）です。本番と同じつもりで面接してください。

【面接官としての性格】
${args.styleInstruction}

【面接の形式】
${d.format}

【最初の挨拶】
本番の面接官として自然にあいさつし、最初の質問（名前や自己紹介）をする。例：「それでは面接を始めます。${d.stage === "中学" ? "受験番号と名前を教えてください。" : "まず、簡単に自己紹介をお願いします。"}」

【必ず聞くこと（順番は会話の流れで自然に変えてよい）】
${d.topics.map((t) => `- ${t}`).join("\n")}

【この面接で見ていること・深掘りのしかた】
${d.focus}

${args.schoolInfo ? `【${args.schoolName ?? "志望校"}について調べたこと（この学校の面接官として、特色・教育方針・求める生徒像に合わせた質問をする。合っているかも見る）】\n${args.schoolInfo}\n` : ""}
【会話のルール】
- 相手は${d.stage === "中学" ? "中学生" : d.stage === "高校" ? "高校生" : "学生"}。質問は${d.stage === "中学" ? "やさしい言葉で、短く" : "簡潔に"}。今の学校のことは「${stageWord}」と呼ぶ
- すでに話した内容は聞き直さない
- ${args.depthInstruction}
- 返答は2〜3文。相づちは短く、すぐ次の質問へ
- 重要：あなたは面接官に徹する。評価・アドバイス・「良い点は〜」といったフィードバックは面接中に一切口にしない（終わってから別に行う）
- 実在しない学校の情報や、調べていない数字（倍率・偏差値など）を作り話しない

【終了条件】
- 必ず聞くことを一通り聞けたら「以上で面接を終わります。お疲れさまでした」と言って終える
- ${args.timeInstruction}

日本語で話してください。`;
}
